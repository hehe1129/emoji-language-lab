import assert from 'node:assert/strict';
const base=process.argv[2]||'http://localhost:8788';
let checks=0;
async function api(path,method='GET',body,session){const r=await fetch(base+'/api/'+path,{method,headers:{'Content-Type':'application/json',...(session?{Authorization:'Bearer '+session.token}:{})},body:body===undefined?undefined:JSON.stringify(body)});return {status:r.status,body:await r.json()};}
const check=(condition,message)=>{assert.ok(condition,message);checks++;console.log('PASS',message);};
const status=await api('status');check(status.body.mode==='public','server has actual D1 binding');
const a=(await api('sessions','POST',{})).body,b=(await api('sessions','POST',{})).body;
const payload=(levelId,sequence,id=crypto.randomUUID())=>({id,levelId,sequence,sessionId:a.id});
check((await api('works','POST',payload('04',['gift']),a)).status===403,'server rejects missing prerequisite');
check((await api('works','POST',payload('01',[]),a)).status===400,'empty sequence rejected');
check((await api('works','POST',payload('01',Array(7).fill('cat')),a)).status===400,'over limit rejected');
check((await api('works','POST',payload('01',['rocket']),a)).status===400,'foreign asset rejected');
check((await api('works','POST',payload('99',['cat']),a)).status===400,'unknown level rejected');
check((await api('works','POST',payload('01',['cat']))).status===401,'missing credential rejected');
const first=payload('01',['cat','cat','moon','sleep']);
const before=(await api('works?level=01')).body.total;
const retries=await Promise.all(Array.from({length:4},()=>api('works','POST',first,a)));
check(retries.every(r=>r.status<300&&r.body.id===first.id),'concurrent same-ID retries return same saved record');
check((await api('works?level=01')).body.total===before+1,'same-ID retry creates exactly one work');
check((await api('works','POST',{...first,sequence:['moon']},a)).status===409,'same ID cannot overwrite content');
check((await api('works','POST',{...first,sessionId:b.id},b)).status===409,'another session cannot reuse submission ID');
const shared=(await api('works?level=01')).body.works.find(w=>w.id===first.id);
check(JSON.stringify(shared.sequence)===JSON.stringify(first.sequence),'public read preserves ordered repeated IDs');
check(!('sessionId' in shared)&&!('session_id' in shared)&&!('token' in shared),'public list hides internal credentials');
for(const method of ['PUT','PATCH','DELETE'])check((await api('works',method,first,a)).status===405,method+' prohibited');
check((await api('works','POST',payload('05',['earth']),a)).status===403,'03 independently gates 05');
check((await api('works','POST',payload('03',['rocket','moon','sunrise']),a)).status===201,'03 unlocks after 01');
check((await api('works','POST',payload('05',['earth','heart']),a)).status===201,'05 unlocks after 03');
check((await api('works','POST',payload('04',['gift']),a)).status===403,'other branch does not unlock 04');
check((await api('works','POST',payload('02',['rain','house']),a)).status===201,'02 unlocks after 01');
check((await api('works','POST',payload('04',['smile','friends']),a)).status===201,'04 unlocks after 02');
check((await api('sessions?id='+a.id,'GET',undefined,a)).body.works.length===5,'session recovery returns all five saved works');
check((await api('sessions?id='+b.id,'GET',undefined,b)).body.works.length===0,'new anonymous session has no progress');
check((await api('works?level=01')).body.works.some(w=>w.id===first.id),'new session does not erase public works');
check((await api('sessions?id='+a.id,'GET',undefined,b)).status===401,'one anonymous session cannot read another private review');
check((await api('works?level=01&page=-1')).status===400,'invalid page rejected');
console.log(JSON.stringify({base,checks,result:'passed'}));
